import { useMemo } from "react";
import { PrismLight as SyntaxHighlighter } from "react-syntax-highlighter";
import cpp from "react-syntax-highlighter/dist/esm/languages/prism/cpp";
import go from "react-syntax-highlighter/dist/esm/languages/prism/go";
import python from "react-syntax-highlighter/dist/esm/languages/prism/python";
import { vscDarkPlus } from "react-syntax-highlighter/dist/esm/styles/prism";

SyntaxHighlighter.registerLanguage("cpp", cpp);
SyntaxHighlighter.registerLanguage("go", go);
SyntaxHighlighter.registerLanguage("python", python);

type Props = {
  code: string;
  lang: string;
  highlightRanges?: number[][];
};

const HL_LANGUAGES: Record<string, string> = {
  python: "python",
  go: "go",
  cpp: "cpp",
};

/** Syntax highlighted solution with dimmed lines outside the
 * highlight ranges (0-indexed half-open pairs, as generated by
 * scripts/update_progress.py). */
export function CodeViewer({ code, lang, highlightRanges }: Props) {
  const language = HL_LANGUAGES[lang] ?? "python";

  const ranges = useMemo(
    () => highlightRanges ?? [],
    [highlightRanges],
  );

  const isHighlighted = (lineNumber: number): boolean => {
    if (ranges.length === 0) return true;
    const index = lineNumber - 1;
    return ranges.some(([start, end]) => index >= start && index < end);
  };

  return (
    <div className="min-w-0 overflow-x-auto py-[1lh]">
      <SyntaxHighlighter
        language={language}
        style={vscDarkPlus}
        showLineNumbers
        wrapLines
        lineProps={(lineNumber: number) => ({
          style: {
            opacity: isHighlighted(lineNumber) ? 1 : 0.25,
            transition: "opacity 0.3s",
            display: "block",
          },
        })}
        customStyle={{
          background: "transparent",
          margin: 0,
          padding: 0,
          fontSize: "0.8125rem",
          lineHeight: "1.5",
        }}
      >
        {code}
      </SyntaxHighlighter>
    </div>
  );
}
